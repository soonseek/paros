import { describe, expect, it } from "vitest";

import {
  detectWooriMergedLedgerProfile,
  maybeNormalizeWooriMergedLedgerTable,
} from "~/lib/woori-merged-ledger";

const headers = [
  "No.",
  "거래일시적요",
  "기재내용",
  "지급(원)",
  "입금(원)",
  "거래후잔액(원)",
  "취급점",
  "메모수표·어음·증권금액(",
];

describe("woori-merged-ledger", () => {
  it("우리은행 병합형 OCR 붕괴 패턴을 엄격하게 감지한다", () => {
    const rows = [
      ["1", "2025.01.08 17:10:", "F/B출금", "우리캐001", "407,000 0", "-49,146,022", "중소벤처기업진", "0"],
      ["2 2025.01.09", "11:01: 자동이체", "", "퇴직연금-천진호(영 100,000", "0", "", "-49,246,022 중소벤처기업진", "0"],
      ["3 2025.01.09", "12:48: 인터넷", "농협행복한재가장기", "78,220", "0", "-49,324,242", "중소벤처기업진", "0"],
    ];

    expect(detectWooriMergedLedgerProfile(headers, rows)).toBe(true);
  });

  it("정상 구조 문서는 감지하지 않는다", () => {
    const rows = [
      ["1", "2025.01.08 17:10: F/B출금", "우리캐001", "407,000", "0", "-49,146,022", "중소벤처기업진", "0"],
      ["2", "2025.01.09 11:01: 자동이체", "퇴직연금-천진호(영", "100,000", "0", "-49,246,022", "중소벤처기업진", "0"],
    ];

    expect(detectWooriMergedLedgerProfile(headers, rows)).toBe(false);
  });

  it("샘플 행을 템플릿 친화적인 열 구조로 복원한다", () => {
    const rows = [
      ["1", "2025.01.08 17:10:", "F/B출금", "우리캐001", "407,000 0", "-49,146,022", "중소벤처기업진", "0"],
      ["2 2025.01.09", "11:01: 자동이체", "", "퇴직연금-천진호(영 100,000", "0", "", "-49,246,022 중소벤처기업진", "0"],
      ["8", "2025.01.16 16:50; 모바일", "천진호", "0", "3,900,000", "-43,783,971 카카오뱅크(090", "", "0"],
    ];

    const normalized = maybeNormalizeWooriMergedLedgerTable({ headers, rows, totalRows: rows.length });

    expect(normalized.rows[0]).toEqual([
      "1",
      "2025.01.08 17:10: F/B출금",
      "우리캐001",
      "407,000",
      "0",
      "-49,146,022",
      "중소벤처기업진",
      "0",
    ]);

    expect(normalized.rows[1]).toEqual([
      "2",
      "2025.01.09 11:01: 자동이체",
      "퇴직연금-천진호(영",
      "100,000",
      "0",
      "-49,246,022",
      "중소벤처기업진",
      "0",
    ]);

    expect(normalized.rows[2]).toEqual([
      "8",
      "2025.01.16 16:50: 모바일",
      "천진호",
      "0",
      "3,900,000",
      "-43,783,971",
      "카카오뱅크(090",
      "0",
    ]);
  });
});